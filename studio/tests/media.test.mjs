import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import * as Y from 'yjs';
import WebSocket from 'ws';
import { createStudioServer } from '../server.mjs';
import { issueStudioToken } from '../../shared/studio-token.mjs';
import { webpSize } from '../media.mjs';
import { vector } from '../store.mjs';
import { prepareTemplate } from '../template.mjs';

const picture = Buffer.from('UklGRi4AAABXRUJQVlA4ICIAAABwAQCdASoMAAgAAUAiJYgCdAF1AAD+8dvAB/i37R/e2FAA', 'base64');

test('shared image bank protects uploads, preserves concurrent text and comments, rejects stale choices and survives restart', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'althea-media-'));
  const options = { port: 0, secret: 'studio-media-test-secret-over-thirty-two', allowed: ['juho', 'julia'], origins: ['https://editor.example'], login: { check() {} }, dataDir: directory };
  let server = await createStudioServer(options);
  t.after(async () => { await server.close(); await rm(directory, { recursive: true }); });
  const token = issueStudioToken({ login: 'julia', name: 'Julia' }, options.secret);
  const headers = { authorization: `Bearer ${token}`, origin: options.origins[0] };
  let base = `http://127.0.0.1:${server.port}`;
  const get = async path => (await fetch(base + path, { headers })).json();
  const post = (path, body) => fetch(base + path, { method: 'POST', headers: { ...headers, 'content-type': 'application/json' }, body: JSON.stringify(body) });
  assert.equal((await fetch(base + '/api/media')).status, 401);
  assert.equal((await fetch(base + '/api/media', { headers: { ...headers, origin: 'https://other.example' } })).status, 403);
  const bank = await get('/api/media'); assert.ok(bank.images.length >= 8);
  const slot = bank.slots.find(item => item.kind === 'background'); assert.equal(slot.label, 'Yläosan taustakuva');
  const socket = new WebSocket(base.replace('http', 'ws') + '/sync/althea-uusi', ['althea-auth.' + token], { origin: options.origins[0] });
  await new Promise((resolve, reject) => { socket.once('open', resolve); socket.once('error', reject); });
  socket.send(Buffer.from([6]));
  const notice = new Promise(resolve => socket.on('message', bytes => { if (bytes[0] === 6) resolve(); }));
  const uploaded = await fetch(base + '/api/media-upload?name=Testikuva.png', { method: 'POST', headers: { ...headers, 'content-type': 'image/webp' }, body: picture });
  assert.equal(uploaded.status, 200); const { entry } = await uploaded.json();
  await Promise.race([notice, new Promise((_, reject) => { const timeout = setTimeout(() => reject(new Error('Missing shared library notification')), 3000); timeout.unref(); })]);
  socket.close();
  const duplicate = await fetch(base + '/api/media-upload?name=Kopio.webp', { method: 'POST', headers, body: picture });
  assert.equal((await duplicate.json()).duplicate, true);
  assert.equal((await get('/api/media')).images.length, bank.images.length + 1);
  const file = await fetch(base + '/api/media-file/' + entry.id, { headers });
  assert.equal(file.headers.get('content-type'), 'image/webp'); assert.deepEqual(Buffer.from(await file.arrayBuffer()), picture);
  assert.equal((await fetch(base + '/api/media-file/' + entry.id)).status, 401);
  assert.equal((await fetch(base + '/api/media-file/' + '0'.repeat(64), { headers })).status, 404);
  const initial = server.store.export();
  assert.equal((await (await post('/api/export', { vector: initial.vector })).json()).assets.length, 0);
  const field = server.store.manifest.fields[0].id;
  const candidate = new Y.Doc(); Y.applyUpdate(candidate, Y.encodeStateAsUpdate(server.store.doc));
  const text = candidate.getXmlFragment(field).get(0).get(0); text.insert(text.length, ' Julian samanaikainen muutos.');
  candidate.getMap('comments').set('image-comment', { fieldId: field, body: 'Tekstikommentti säilyy.', author: 'Julia', createdAt: new Date().toISOString(), resolved: false });
  server.store.apply(Y.encodeStateAsUpdate(candidate, Y.encodeStateVector(server.store.doc)), null, { sub: 'julia', name: 'Julia' }); candidate.destroy();
  const latest = JSON.stringify(server.store.fields()), history = server.store.fieldHistory(field);
  const assignment = { nodeId: slot.id, imageHash: slot.imageHash, mediaId: entry.id, alt: 'Vihreä testikuva', position: '50% 20%' };
  assert.equal((await post('/api/media-assign', assignment)).status, 200);
  assert.equal(JSON.stringify(server.store.fields()), latest); assert.deepEqual(server.store.fieldHistory(field), history);
  assert.equal(server.store.comments.get('image-comment').body, 'Tekstikommentti säilyy.');
  let nextBank = await get('/api/media');
  const nextSlot = nextBank.slots.find(item => item.id === slot.id);
  assert.equal(nextSlot.src, entry.path); assert.equal(nextSlot.position, '50% 20%');
  assert.deepEqual(nextBank.slots.filter(item => item.id !== slot.id), bank.slots.filter(item => item.id !== slot.id));
  assert.equal((await post('/api/media-assign', assignment)).status, 409);
  assert.equal((await post('/api/media-assign', { ...assignment, imageHash: nextSlot.imageHash, position: 'url(javascript:x)' })).status, 400);
  assert.equal((await post('/api/media-assign', { ...assignment, imageHash: nextSlot.imageHash, mediaId: '../../secret' })).status, 404);
  assert.equal((await post('/api/export', { vector: initial.vector })).status, 409);
  const snapshot = await (await post('/api/export', { vector: vector(server.store.doc) })).json();
  assert.deepEqual(snapshot.assets, [{ path: entry.path, digest: entry.id, content: picture.toString('base64') }]);
  assert.equal(prepareTemplate(snapshot.html).manifest.layoutHash, snapshot.layoutHash);
  assert.ok(snapshot.html.includes('Julian samanaikainen muutos.'));
  assert.equal((await fetch(base + '/api/media-upload', { method: 'POST', headers, body: '<svg onload="alert(1)"/>' })).status, 400);
  assert.equal((await fetch(base + '/api/media-upload', { method: 'POST', headers, body: Buffer.alloc(2 * 1024 * 1024 + 1) })).status, 413);
  await server.close(); server = await createStudioServer(options); base = `http://127.0.0.1:${server.port}`;
  nextBank = await get('/api/media');
  assert.equal(nextBank.images.length, bank.images.length + 1); assert.deepEqual(nextBank.slots.find(item => item.id === slot.id), nextSlot);
  assert.equal(JSON.stringify(server.store.fields()), latest); assert.equal(server.store.comments.size, 1);
  assert.deepEqual(server.media.read(entry.id), picture);
});

test('image validator rejects oversized dimensions, animation and truncated or executable payloads', () => {
  assert.deepEqual(webpSize(picture), { width: 12, height: 8 });
  const extended = Buffer.alloc(18); extended.write('VP8X'); extended.writeUInt32LE(10, 4);
  extended[8] = 0x20; extended.writeUIntLE(11, 12, 3); extended.writeUIntLE(7, 15, 3);
  const profile = Buffer.alloc(12); profile.write('ICCP'); profile.writeUInt32LE(4, 4); profile.write('test', 8);
  const colorPicture = Buffer.concat([picture.subarray(0, 12), extended, profile, picture.subarray(12)]);
  colorPicture.writeUInt32LE(colorPicture.length - 8, 4);
  assert.deepEqual(webpSize(colorPicture), { width: 12, height: 8 });
  const animated = Buffer.from(colorPicture); animated[20] |= 0x02; assert.throws(() => webpSize(animated), /Liikkuvia/);
  const large = Buffer.from(picture); large.writeUInt16LE(4096, 26); assert.throws(() => webpSize(large), /liian suuri/);
  assert.throws(() => webpSize(picture.subarray(0, -1)), /kelvollinen/);
  assert.throws(() => webpSize(Buffer.from('<svg/>')), /kelvollinen/);
  const executable = Buffer.from(picture); executable.write('EXIF', 12); assert.throws(() => webpSize(executable), /ei tueta/);
});
